<?php
declare(strict_types=1);

require_once __DIR__ . '/security.php';
require_once __DIR__ . '/db.php';
require_once __DIR__ . '/php-compat.php';

const ADMIN_IDLE_TIMEOUT = 1800;
const ADMIN_ABSOLUTE_TIMEOUT = 28800;

function admin_setup_allowed(): bool
{
    $remote = trim((string) ($_SERVER['REMOTE_ADDR'] ?? ''));
    return $remote === '127.0.0.1' || $remote === '::1' || str_starts_with($remote, '127.');
}

function ensure_admin_schema(): void
{
    global $pdo;
    static $ready = false;
    if ($ready) {
        return;
    }

    if ($pdo->getAttribute(PDO::ATTR_DRIVER_NAME) === 'pgsql') {
        $pdo->exec("CREATE TABLE IF NOT EXISTS admin_users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username VARCHAR(80) NOT NULL DEFAULT 'admin' UNIQUE,
            password_hash VARCHAR(255) NOT NULL,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP NULL DEFAULT NULL
        )");
    } else {
        $pdo->exec("CREATE TABLE IF NOT EXISTS admin_users (
            id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
            username VARCHAR(80) NOT NULL DEFAULT 'admin',
            password_hash VARCHAR(255) NOT NULL,
            created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
            updated_at DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
            PRIMARY KEY (id),
            UNIQUE KEY uniq_admin_users_username (username)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");
    }

    $existing = $pdo->query("SELECT 1 FROM admin_users WHERE username = 'admin' LIMIT 1")->fetch();
    if (!$existing) {
        $seedPassword = trim((string) (getenv('SKUSHDROP_ADMIN_PASSWORD') ?: ($_ENV['SKUSHDROP_ADMIN_PASSWORD'] ?? '')));
        if (strlen($seedPassword) >= 12) {
            $statement = $pdo->prepare('INSERT INTO admin_users (username, password_hash) VALUES (:username, :password_hash)');
            $statement->execute([
                ':username' => 'admin',
                ':password_hash' => password_hash($seedPassword, PASSWORD_DEFAULT),
            ]);
        }
    }

    $ready = true;
}

function start_admin_session(): void
{
    apply_security_headers(true);

    if (session_status() === PHP_SESSION_ACTIVE) {
        return;
    }

    $secure = !empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off';
    ini_set('session.use_strict_mode', '1');
    ini_set('session.use_only_cookies', '1');
    ini_set('session.use_trans_sid', '0');
    session_name('skushdrop_admin');
    session_set_cookie_params([
        'lifetime' => 0,
        'path' => '/',
        'secure' => $secure,
        'httponly' => true,
        'samesite' => 'Strict',
    ]);
    session_start();
}

function admin_credentials(): array
{
    global $pdo;
    ensure_admin_schema();

    $statement = $pdo->prepare('SELECT id, username, password_hash, created_at FROM admin_users WHERE username = :username LIMIT 1');
    $statement->execute([':username' => 'admin']);
    $credentials = $statement->fetch();
    return is_array($credentials) ? $credentials : [];
}

function admin_has_credentials(): bool
{
    return isset(admin_credentials()['password_hash']);
}

function admin_create_password(string $password): bool
{
    if (strlen($password) < 12) {
        return false;
    }

    global $pdo;
    ensure_admin_schema();

    $hash = password_hash($password, PASSWORD_DEFAULT);
    if (!is_string($hash)) {
        return false;
    }

    $existing = $pdo->query("SELECT id FROM admin_users WHERE username = 'admin' LIMIT 1")->fetch();
    if ($existing) {
        $statement = $pdo->prepare('UPDATE admin_users SET password_hash = :password_hash, updated_at = NOW() WHERE username = :username');
        $statement->execute([
            ':username' => 'admin',
            ':password_hash' => $hash,
        ]);
    } else {
        $statement = $pdo->prepare('INSERT INTO admin_users (username, password_hash) VALUES (:username, :password_hash)');
        $statement->execute([
            ':username' => 'admin',
            ':password_hash' => $hash,
        ]);
    }

    return true;
}

function admin_is_authenticated(): bool
{
    start_admin_session();
    if (!admin_has_credentials()) {
        return false;
    }

    if (empty($_SESSION['admin_authenticated'])) {
        return false;
    }

    $now = time();
    $createdAt = (int) ($_SESSION['admin_authenticated_at'] ?? 0);
    $lastActivity = (int) ($_SESSION['admin_last_activity'] ?? 0);
    if ($createdAt === 0 || $lastActivity === 0
        || ($now - $lastActivity) > ADMIN_IDLE_TIMEOUT
        || ($now - $createdAt) > ADMIN_ABSOLUTE_TIMEOUT) {
        admin_logout();
        return false;
    }

    $_SESSION['admin_last_activity'] = $now;
    return true;
}

function admin_login(string $password): bool
{
    start_admin_session();
    $credentials = admin_credentials();
    $valid = isset($credentials['password_hash'])
        && password_verify($password, (string) $credentials['password_hash']);

    if (!$valid) {
        return false;
    }

    admin_mark_authenticated();
    return true;
}

function admin_mark_authenticated(): void
{
    start_admin_session();
    session_regenerate_id(true);
    $_SESSION['admin_authenticated'] = true;
    $_SESSION['admin_authenticated_at'] = time();
    $_SESSION['admin_last_activity'] = time();
    unset($_SESSION['admin_csrf']);
}

function admin_logout(): void
{
    start_admin_session();
    $_SESSION = [];
    if (ini_get('session.use_cookies')) {
        $params = session_get_cookie_params();
        setcookie(session_name(), '', [
            'expires' => time() - 42000,
            'path' => $params['path'],
            'domain' => $params['domain'],
            'secure' => $params['secure'],
            'httponly' => true,
            'samesite' => 'Strict',
        ]);
    }
    session_destroy();
}

function admin_csrf_token(): string
{
    start_admin_session();
    if (empty($_SESSION['admin_csrf'])) {
        $_SESSION['admin_csrf'] = bin2hex(random_bytes(32));
    }
    return (string) $_SESSION['admin_csrf'];
}

function admin_csrf_is_valid(string $token): bool
{
    return hash_equals(admin_csrf_token(), $token);
}
